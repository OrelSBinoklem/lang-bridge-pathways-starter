// Mechanical catalog generation. No renderer is created and no browser/GPU work is performed.
// Run: node scripts/build-scene-catalog.mjs [--check]
import { register } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
register(new URL('./scene-catalog-loader.mjs', import.meta.url));
const base = new URL('../src/features/course/effects/scenes/', import.meta.url);
const source = await readFile(new URL('sceneSources.ts', base), 'utf8');
const { ALL_SCENES } = await import(new URL('sceneSources.ts', base));
const bindings = new Map();
for (const [, names, path] of source.matchAll(/import \{([^}]+)\} from '([^']+)'/g)) {
  const module = await import(new URL(path + (path === './cinematic' ? '/index.ts' : '.ts'), base));
  for (const name of names.split(',').map(n => n.trim())) {
    const scenes = Array.isArray(module[name]) ? module[name] : [module[name]];
    for (const scene of scenes) bindings.set(scene, { path, name, array: Array.isArray(module[name]) });
  }
}
const literal = value => JSON.stringify(value, (key, item) => item === Infinity ? '__INFINITY__' : item).replaceAll('"__INFINITY__"', 'Infinity');
const entries = ALL_SCENES.map(scene => {
  const binding = bindings.get(scene);
  if (!binding) throw new Error(`Missing source binding: ${scene.id}`);
  const { create, fragment, ...meta } = scene;
  const selection = binding.array ? `m.${binding.name}.find(s => s.id === ${JSON.stringify(scene.id)})!` : `m.${binding.name}`;
  return `  lazyScene(${literal(meta)}, () => import('${binding.path}').then(m => ${selection})),`;
});
const catalog = `// Generated by scripts/build-scene-catalog.mjs; edit sceneSources or scene definitions, then regenerate.\nimport { lazyScene } from './lazyScene';\nexport const ALL_SCENES = [\n${entries.join('\n')}\n];\n`;
const settingsModules = {
  canvasScenes4: ['LED_MODE_LABELS', 'LED_STYLE_LABELS'],
  kaleidoscope: ['KALEIDOSCOPE_SETTINGS', 'KALEIDOSCOPE_TABS'],
  fountain: ['FOUNTAIN_SETTINGS', 'FOUNTAIN_WATER_MODES'],
  glassFountain: ['GLASS_FOUNTAIN_CHOICES', 'GLASS_FOUNTAIN_SETTINGS'],
  dragonSmoke: ['DRAGON_SMOKE_SETTINGS'], dragonBurner: ['DRAGON_BURNER_CHOICES', 'DRAGON_BURNER_SETTINGS'],
  gems: ['GEMS_SETTINGS'], ledCube: ['LED_FIGURE_CHOICES', 'LED_FIGURE_SETTINGS'],
  foggedGlass: ['FOGGED_GLASS_SETTINGS', 'FOG_STREET_MODES'], snowLantern: ['SNOW_LANTERN_CHOICES', 'SNOW_LANTERN_SETTINGS'],
  opticsLab: ['OPTICS_LASER_LABELS', 'OPTICS_SET_LABELS'],
};
const settings = ['// Generated by scripts/build-scene-catalog.mjs. Data only: no scene engine is imported at runtime.'];
for (const [path, names] of Object.entries(settingsModules)) {
  const module = await import(new URL(path + '.ts', base));
  for (const name of names) settings.push(`export const ${name} = ${literal(module[name])} as unknown as typeof import('./${path}').${name};`);
}
for (const [name, content] of [['sceneCatalog.generated.ts', catalog], ['sceneSettings.generated.ts', settings.join('\n') + '\n']]) {
  if (process.argv.includes('--check')) {
    if (await readFile(new URL(name, base), 'utf8') !== content) throw new Error(`Stale ${name}: regenerate the scene catalog`);
  } else await writeFile(new URL(name, base), content);
}
console.log(`${ALL_SCENES.length} scene descriptors; ${Buffer.byteLength(catalog)} bytes, shader/physics engines deferred. Catalog ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
