const lowerMap = Object.fromEntries(
  Object.entries(map).map(([key, value]) => [key.toLowerCase(), value]),
);

function translateValue(value) {
  if (Array.isArray(value)) return value.map(translateValue);
  if (value && typeof value === 'object') return translateObject(value);
  if (typeof value !== 'string') return value;
  return map[value] ?? lowerMap[value.toLowerCase()] ?? value;
}

function preserveValue(value) {
  if (Array.isArray(value)) return value.map(preserveValue);
  if (value && typeof value === 'object') return preserveObject(value);
  return value;
}

function translateObject(obj) {
  if (Array.isArray(obj)) return obj.map(translateValue);
  return translateObjectWithMode(obj, true);
}

function preserveObject(obj) {
  if (Array.isArray(obj)) return obj.map(preserveValue);
  return translateObjectWithMode(obj, false);
}

function translateObjectWithMode(obj, shouldTranslateKeys) {
  if (Array.isArray(obj)) {
    return obj.map(shouldTranslateKeys ? translateValue : preserveValue);
  }
  const out = {};
  for (const [key, value] of Object.entries(obj)) {
    if (key === 'category' || key === 'sub_category' || key === 'translated' || key === 'difficult_translation') {
      out[key] = translateValue(value);
    } else {
      out[key] = preserveValue(value);
    }
  }
  return out;
}

