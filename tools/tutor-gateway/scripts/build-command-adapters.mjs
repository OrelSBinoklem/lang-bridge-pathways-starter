import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

// Deliberately use the already installed frontend compiler, not runtime TS loading.
const root = fileURLToPath(new URL('../../../', import.meta.url));
const require = createRequire(new URL('../../../frontend/package.json', import.meta.url));
const ts = require('typescript');
const paths = ['src/commands/adapters/contracts.ts', 'src/commands/adapters/CommandAdapterRegistry.ts', 'src/agent/ToolLoopController.ts'];
const files = paths.map(path => resolve(root, 'tools/tutor-gateway', path));
const options = { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler, strict: true, skipLibCheck: true,
  resolveJsonModule: true, allowSyntheticDefaultImports: true, declaration: true,
  newLine: ts.NewLineKind.LineFeed, types: [], lib: ['lib.es2022.d.ts', 'lib.dom.d.ts'] };
const host = ts.createCompilerHost(options);
// Source is .ts; the executable/declaration contract is explicitly .mjs/.d.mts.
host.resolveModuleNames = (names, containingFile) => names.map(name => {
  const source = name.endsWith('.mjs') ? resolve(dirname(containingFile), name.replace(/\.mjs$/, '.ts')) : '';
  return files.includes(source) ? { resolvedFileName: source, extension: ts.Extension.Ts }
    : ts.resolveModuleName(name, containingFile, options, host).resolvedModule;
});
const program = ts.createProgram(files, options, host);
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) {
  process.stderr.write(ts.formatDiagnosticsWithColorAndContext(diagnostics, { getCurrentDirectory: () => root, getCanonicalFileName: x => x, getNewLine: () => '\n' }));
  process.exit(1);
}
let stale = false;
program.emit(undefined, (file, text) => {
  if (!/\.(?:js|d\.ts)$/.test(file)) return; // Never copy the shared JSON.
  const target = file.endsWith('.d.ts') ? file.replace(/\.d\.ts$/, '.d.mts') : file.replace(/\.js$/, '.mjs');
  const output = '// Generated by scripts/build-command-adapters.mjs; edit the .ts source.\n' + text;
  if (process.argv.includes('--check')) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== output) { process.stderr.write(`Stale generated file: ${target}\n`); stale = true; }
  } else writeFileSync(target, output);
});
if (stale) process.exit(1);
process.stdout.write('Command adapters and ToolLoopController: typecheck and generated runtime OK.\n');
